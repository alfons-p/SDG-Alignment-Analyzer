def get_targets_for_sdg(sdg_num: int) -> Dict[str, Dict[str, Any]]:
    """Return all targets for a given SDG number."""
    return {
        tid: t for tid, t in SDG_TARGET_DEFINITIONS.items()
        if t["sdg_num"] == sdg_num
    }


def get_all_target_ids() -> List[str]:
    """Return sorted list of all target IDs."""
    return sorted(SDG_TARGET_DEFINITIONS.keys())
